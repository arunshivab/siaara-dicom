#!/usr/bin/env python3
"""Generates src/clinical/codes_data.inc from the DICOM standard's DocBook XML (PS3.16).

Usage:
    python3 tools/gen_codes.py <part16.xml> <output .inc>

Source (download from https://dicom.nema.org/medical/dicom/current/source/docbook/):
    part16/part16.xml : Context Group tables "table_CID_<n>" (Annex B) and the DICOM Controlled
                        Terminology table D-1 (Annex D) for code meanings of individual DCM codes.

What is generated (and nothing else is hand-typed in the library):
  - the Context Groups listed in CIDS: every row (scheme designator, code value, code meaning),
    plus the group's version and UID;
  - the DCM codes listed in DCM_CONCEPTS (concept names used by the writers), with their meaning
    taken from table D-1.

Only the Python standard library is used. The output is deterministic so CI can check that the
committed file matches the generator.
"""
import re
import sys
import xml.etree.ElementTree as ET

DB = "{http://docbook.org/ns/docbook}"
XML_ID = "{http://www.w3.org/XML/1998/namespace}id"

# (C++ identifier suffix, CID number)
CIDS = [
    ("KeyObjectSelectionDocumentTitle", 7010),
    ("RejectedForQualityReasons", 7011),
]

# (C++ identifier, DCM code value) - concept names the writers need (TID 2010 row 3 etc.).
DCM_CONCEPTS = [
    ("kKeyObjectDescription", "113012"),
]


def text(node):
    s = "".join(node.itertext())
    s = s.replace("​", "").replace(" ", " ")
    return re.sub(r"\s+", " ", s).strip()


def cpp_str(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.extend("\\x%02X" % b for b in ch.encode("utf-8"))
            out.append('""')  # stop the hex escape from swallowing following hex digits
    return '"' + "".join(out) + '"'


def rows_of(table):
    head = [text(th) for th in table.iter(DB + "th")]
    body = table.find(DB + "tbody")
    rows = []
    for tr in body.findall(DB + "tr"):
        rows.append([text(td) for td in tr.findall(DB + "td")])
    return head, rows


def section_field(section, name):
    for entry in section.iter(DB + "varlistentry"):
        term = entry.find(DB + "term")
        if term is not None and text(term).rstrip(":") == name:
            return text(entry.find(DB + "listitem"))
    return ""


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    root = ET.parse(sys.argv[1]).getroot()
    tables = {t.get(XML_ID): t for t in root.iter(DB + "table") if t.get(XML_ID)}
    sections = {s.get(XML_ID): s for s in root.iter(DB + "section") if s.get(XML_ID)}

    out = []
    out.append("// Generated by tools/gen_codes.py from DICOM PS3.16 (part16.xml). Do not edit.")
    out.append("// Each entry: coding scheme designator, code value, code meaning.")
    for ident, cid in CIDS:
        table = tables.get("table_CID_%d" % cid)
        if table is None:
            raise SystemExit("CID %d not found" % cid)
        head, rows = rows_of(table)
        try:
            ci_s = head.index("Coding Scheme Designator")
            ci_v = head.index("Code Value")
            ci_m = head.index("Code Meaning")
        except ValueError:
            raise SystemExit("CID %d: unexpected columns %r" % (cid, head))
        sec = sections.get("sect_CID_%d" % cid)
        version = section_field(sec, "Version") if sec is not None else ""
        uid = section_field(sec, "UID") if sec is not None else ""
        out.append("")
        out.append("// CID %d %s, version %s, UID %s" % (cid, text(table.find(DB + "caption")), version, uid))
        out.append("inline constexpr CodeEntry kCid%d[] = {" % cid)
        for r in rows:
            if len(r) <= max(ci_s, ci_v, ci_m) or not r[ci_v]:
                continue
            out.append("    {%s, %s, %s}," % (cpp_str(r[ci_s]), cpp_str(r[ci_v]), cpp_str(r[ci_m])))
        out.append("};")
        out.append("inline constexpr std::string_view kCid%dVersion = %s;" % (cid, cpp_str(version)))
        out.append("inline constexpr std::string_view kCid%dUid = %s;" % (cid, cpp_str(uid)))
        out.append("inline constexpr int kCid%s = %d;" % (ident, cid))

    d1 = tables.get("table_D-1")
    if d1 is None:
        raise SystemExit("table D-1 not found")
    head, rows = rows_of(d1)
    vi, mi = head.index("Code Value"), head.index("Code Meaning")
    meanings = {r[vi]: r[mi] for r in rows if len(r) > max(vi, mi)}
    out.append("")
    out.append("// DCM concepts used by the writers (PS3.16 table D-1).")
    for ident, value in DCM_CONCEPTS:
        if value not in meanings:
            raise SystemExit("DCM %s not in table D-1" % value)
        out.append("inline constexpr CodeEntry %s{\"DCM\", %s, %s};" % (ident, cpp_str(value), cpp_str(meanings[value])))
    out.append("")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
