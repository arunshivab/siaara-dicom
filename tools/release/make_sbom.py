#!/usr/bin/env python3
"""Writes an SPDX 2.3 JSON SBOM for one SIAARA release package (standard library only).

    python3 tools/release/make_sbom.py --stage stage/siaara-0.1.0-linux-x64 --version 0.1.0 \
        --platform linux-x64 --commit <git sha> --out siaara-0.1.0-linux-x64.spdx.json

Describes:
  - the package (every file in the staged folder, with SHA-1 and SHA-256);
  - the toolkit's own components (the source modules compiled into the library);
  - the data the toolkit embeds, generated at development time from published standards and
    mapping tables (DICOM PS3.6/PS3.7 dictionary, PS3.15 de-identification table, PS3.16 codes,
    PS3.6 Annex B palettes, Unicode/WHATWG character set mappings);
  - the operating-system libraries the binaries load at run time: those recorded in the binaries
    (readelf -d / otool -L / dumpbin /dependents, through tools/ci/check_binaries.py), plus the
    ones loaded on demand with dlopen / LoadLibrary (the system OpenSSL 3 on Linux, ncrypt.dll on
    Windows).
No license is asserted for the toolkit itself: the project has not chosen one yet (NOASSERTION).
The creation time comes from SOURCE_DATE_EPOCH, so the output is reproducible.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
REPO_URL = "https://github.com/arunshivab/siaara-dicom"

COMPONENTS = [
    ("core", "Data set model, Part 10 reader and writer, file I/O, transfer syntaxes"),
    ("dict", "Data dictionary and UID registry"),
    ("codec", "DEFLATE, RLE, JPEG, JPEG-LS, JPEG 2000 / HTJ2K codecs"),
    ("image", "Pixel pipeline: frames, LUTs, colour, overlays, rendering"),
    ("charset", "Specific Character Set decoding and encoding"),
    ("net", "DICOM upper layer, DIMSE services, TLS adapter over the OS TLS stack"),
    ("web", "HTTP/1.1, DICOMweb, DICOM JSON and XML models"),
    ("store", "Local instance store, index journal, DICOMDIR"),
    ("deid", "De-identification (PS3.15 Annex E)"),
    ("clinical", "Clinical objects: geometry, SUV, ROI, GSPS, SR/KOS, SEG, RT Structure Set"),
    ("capi", "Stable C API"),
]

EMBEDDED_DATA = [
    ("dicom-ps3.6-ps3.7", "DICOM PS3.6 data dictionary and PS3.7 command dictionary (generated by tools/gen_dictionary.py)",
     "https://dicom.nema.org/medical/dicom/current/source/docbook/part06/part06.xml"),
    ("dicom-ps3.15-annex-e", "DICOM PS3.15 Table E.1-1 de-identification profile (generated by tools/gen_deid.py)",
     "https://dicom.nema.org/medical/dicom/current/source/docbook/part15/part15.xml"),
    ("dicom-ps3.16-codes", "DICOM PS3.16 context group codes (generated by tools/gen_codes.py)",
     "https://dicom.nema.org/medical/dicom/current/source/docbook/part16/part16.xml"),
    ("dicom-ps3.6-annex-b-palettes", "DICOM PS3.6 Annex B standard colour palettes (generated by tools/gen_palettes.py)",
     "https://dicom.nema.org/medical/dicom/current/source/docbook/part06/part06.xml"),
    ("unicode-whatwg-mappings", "Character set mapping tables from the Unicode Consortium and WHATWG (generated by tools/gen_charsets.py)",
     "https://encoding.spec.whatwg.org/"),
]

# Loaded on demand (never linked), per OS.
ON_DEMAND = {
    "linux": [("libcrypto.so.3", "System OpenSSL 3, loaded with dlopen when TLS is first used"),
              ("libssl.so.3", "System OpenSSL 3, loaded with dlopen when TLS is first used")],
    "windows": [("ncrypt.dll", "CNG key storage, loaded with LoadLibraryEx from System32 for TLS client keys")],
    "macos": [],
}


def spdx_id(text):
    return "SPDXRef-" + re.sub(r"[^A-Za-z0-9.-]", "-", text)


def file_hashes(path):
    sha1, sha256 = hashlib.sha1(), hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            sha1.update(block)
            sha256.update(block)
    return sha1.hexdigest(), sha256.hexdigest()


def is_binary_to_scan(path, osname):
    name = os.path.basename(path)
    if osname == "windows":
        return name.lower().endswith((".dll", ".exe"))
    if osname == "macos":
        return name.endswith(".dylib") or (os.access(path, os.X_OK) and "." not in name)
    return ".so" in name or (os.access(path, os.X_OK) and "." not in name)


def runtime_dependencies(binaries, osname):
    if not binaries:
        return {}
    cmd = [sys.executable, os.path.join(ROOT, "tools", "ci", "check_binaries.py"), "--os", osname, "list"] + binaries
    out = subprocess.run(cmd, stdout=subprocess.PIPE, check=True).stdout.decode("utf-8")
    return json.loads(out)


def build(args):
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))
    created = datetime.datetime.fromtimestamp(epoch, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    osname = args.os or args.platform.split("-")[0]
    pkg_id = "SPDXRef-Package-siaara"
    packages, files, rels = [], [], []
    packages.append({
        "SPDXID": pkg_id, "name": "siaara", "versionInfo": args.version,
        "downloadLocation": REPO_URL, "filesAnalyzed": False,
        "licenseConcluded": "NOASSERTION", "licenseDeclared": "NOASSERTION", "copyrightText": "NOASSERTION",
        "supplier": "NOASSERTION", "primaryPackagePurpose": "LIBRARY",
        "summary": "SIAARA DICOM Toolkit (%s), zero-dependency C++20 DICOM library, C API and tools" % args.platform,
        "comment": "License to be decided by the project; no license is asserted. Built from commit %s." % args.commit,
        "externalRefs": [{"referenceCategory": "PACKAGE-MANAGER", "referenceType": "purl",
                          "referenceLocator": "pkg:github/arunshivab/siaara-dicom@%s" % args.commit}],
    })
    rels.append({"spdxElementId": "SPDXRef-DOCUMENT", "relationshipType": "DESCRIBES", "relatedSpdxElement": pkg_id})

    binaries = []
    for dirpath, dirnames, filenames in os.walk(args.stage):
        dirnames.sort()
        for name in sorted(filenames):
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, args.stage).replace(os.sep, "/")
            sha1, sha256 = file_hashes(path)
            fid = spdx_id("File-" + rel)
            files.append({"SPDXID": fid, "fileName": "./" + rel,
                          "checksums": [{"algorithm": "SHA1", "checksumValue": sha1},
                                        {"algorithm": "SHA256", "checksumValue": sha256}],
                          "licenseConcluded": "NOASSERTION", "copyrightText": "NOASSERTION"})
            rels.append({"spdxElementId": pkg_id, "relationshipType": "CONTAINS", "relatedSpdxElement": fid})
            if is_binary_to_scan(path, osname) and not os.path.islink(path):
                binaries.append(path)

    for mod, desc in COMPONENTS:
        cid = spdx_id("Package-siaara-" + mod)
        packages.append({"SPDXID": cid, "name": "siaara-" + mod, "versionInfo": args.version,
                         "downloadLocation": "%s/tree/%s/src/%s" % (REPO_URL, args.commit, mod),
                         "filesAnalyzed": False, "licenseConcluded": "NOASSERTION", "licenseDeclared": "NOASSERTION",
                         "copyrightText": "NOASSERTION", "supplier": "NOASSERTION", "summary": desc,
                         "primaryPackagePurpose": "SOURCE"})
        rels.append({"spdxElementId": pkg_id, "relationshipType": "CONTAINS", "relatedSpdxElement": cid})
    for name, desc, url in EMBEDDED_DATA:
        did = spdx_id("Package-data-" + name)
        packages.append({"SPDXID": did, "name": name, "versionInfo": "NOASSERTION", "downloadLocation": url,
                         "filesAnalyzed": False, "licenseConcluded": "NOASSERTION", "licenseDeclared": "NOASSERTION",
                         "copyrightText": "NOASSERTION", "supplier": "NOASSERTION", "summary": desc,
                         "primaryPackagePurpose": "OTHER"})
        rels.append({"spdxElementId": pkg_id, "relationshipType": "CONTAINS", "relatedSpdxElement": did})

    deps = runtime_dependencies(binaries, osname)
    seen = {}
    for binary, libs in sorted(deps.items()):
        for lib in libs:
            seen.setdefault(lib, set()).add(os.path.relpath(binary, args.stage).replace(os.sep, "/"))
    own = re.compile(r"(^|/)(lib)?siaara[^/]*$", re.I)
    for lib in sorted(seen):
        if own.search(lib):
            continue
        lid = spdx_id("Package-os-" + os.path.basename(lib))
        packages.append({"SPDXID": lid, "name": os.path.basename(lib), "versionInfo": "NOASSERTION",
                         "downloadLocation": "NOASSERTION", "filesAnalyzed": False,
                         "licenseConcluded": "NOASSERTION", "licenseDeclared": "NOASSERTION",
                         "copyrightText": "NOASSERTION", "supplier": "NOASSERTION",
                         "primaryPackagePurpose": "OPERATING-SYSTEM",
                         "comment": "Operating-system library linked by: %s" % ", ".join(sorted(seen[lib])),
                         "sourceInfo": "Recorded as %s" % lib})
        rels.append({"spdxElementId": pkg_id, "relationshipType": "DEPENDS_ON", "relatedSpdxElement": lid})
    for lib, why in ON_DEMAND.get(osname, []):
        lid = spdx_id("Package-os-" + lib)
        packages.append({"SPDXID": lid, "name": lib, "versionInfo": "NOASSERTION", "downloadLocation": "NOASSERTION",
                         "filesAnalyzed": False, "licenseConcluded": "NOASSERTION", "licenseDeclared": "NOASSERTION",
                         "copyrightText": "NOASSERTION", "supplier": "NOASSERTION",
                         "primaryPackagePurpose": "OPERATING-SYSTEM", "comment": why + " (not linked)."})
        rels.append({"spdxElementId": lid, "relationshipType": "OPTIONAL_DEPENDENCY_OF", "relatedSpdxElement": pkg_id})

    ns_hash = hashlib.sha256(("%s|%s|%s" % (args.version, args.platform, args.commit)).encode()).hexdigest()[:32]
    return {
        "spdxVersion": "SPDX-2.3",
        "dataLicense": "CC0-1.0",
        "SPDXID": "SPDXRef-DOCUMENT",
        "name": "siaara-%s-%s" % (args.version, args.platform),
        "documentNamespace": "%s/spdx/siaara-%s-%s-%s" % (REPO_URL, args.version, args.platform, ns_hash),
        "creationInfo": {"created": created, "creators": ["Tool: siaara-make_sbom.py"],
                         "comment": "Generated from the staged release package and the binaries' recorded dependencies."},
        "packages": packages,
        "files": files,
        "relationships": rels,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", required=True, help="installed package folder")
    ap.add_argument("--version", required=True)
    ap.add_argument("--platform", required=True, help="e.g. linux-x64, windows-arm64, macos-universal")
    ap.add_argument("--commit", default="NOASSERTION")
    ap.add_argument("--os", choices=["linux", "macos", "windows"], help="default: from --platform")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    doc = build(args)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=2, sort_keys=False)
        f.write("\n")
    print("SBOM: %d packages, %d files -> %s" % (len(doc["packages"]), len(doc["files"]), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
