FrameInfo frame(std::uint32_t rows, std::uint32_t cols, std::uint16_t spp, std::uint16_t bits, bool sgn = false) {
    FrameInfo fi;
    fi.rows = rows;
    fi.columns = cols;
    fi.samples_per_pixel = spp;
    fi.bits_stored = bits;
    fi.bits_allocated = bits > 8 ? 16 : 8;
    fi.is_signed = sgn;
    return fi;
}

// Deterministic test image in the native layout: smooth gradients, edges and noise.
std::vector<std::uint8_t> make_image(const FrameInfo& fi, std::uint32_t seed) {
    std::mt19937 rng(seed);
    std::vector<std::uint8_t> out(static_cast<std::size_t>(fi.frame_bytes()));
    const std::size_t bps = fi.bits_allocated / 8u;
    const std::int64_t top = (std::int64_t{1} << fi.bits_stored) - 1;
    const std::size_t n = static_cast<std::size_t>(fi.rows) * fi.columns * fi.samples_per_pixel;
    for (std::size_t i = 0; i < n; ++i) {
        const std::size_t px = i / fi.samples_per_pixel;
        const std::size_t c = i % fi.samples_per_pixel;
        const double x = static_cast<double>(px % fi.columns), y = static_cast<double>(px / fi.columns);
        double v = (std::sin(x / (5.0 + static_cast<double>(c))) + std::cos(y / 7.0) + 2.0) / 4.0 * static_cast<double>(top);
        if ((static_cast<int>(x) / 11 + static_cast<int>(y) / 9) % 3 == 0) v = static_cast<double>(top) - v;
        v += static_cast<double>(static_cast<int>(rng() % 17) - 8) * static_cast<double>(top) / 512.0;
        std::int64_t s = std::clamp<std::int64_t>(std::llround(v), 0, top);
        if (fi.is_signed) s -= std::int64_t{1} << (fi.bits_stored - 1);
        const auto u = static_cast<std::uint32_t>(s) & static_cast<std::uint32_t>(top);
        std::uint32_t stored = u;
        if (fi.is_signed && s < 0) stored = static_cast<std::uint32_t>(s);  // two's complement in bits_allocated
        if (bps == 1) out[i] = static_cast<std::uint8_t>(stored);
        else store_le16(&out[2 * i], static_cast<std::uint16_t>(stored));
    }
    return out;
}

std::int64_t sample(const std::vector<std::uint8_t>& buf, const FrameInfo& fi, std::size_t i) {
    std::uint32_t v = fi.bits_allocated == 8 ? buf[i] : load_le16(&buf[2 * i]);
    const std::uint32_t mask = (1u << fi.bits_stored) - 1u;
    v &= mask;
    if (fi.is_signed && (v >> (fi.bits_stored - 1)) & 1u) return static_cast<std::int64_t>(v) - (std::int64_t{1} << fi.bits_stored);
    return v;
}

double psnr(const std::vector<std::uint8_t>& a, const std::vector<std::uint8_t>& b, const FrameInfo& fi, std::int64_t* maxerr = nullptr) {
    const std::size_t n = static_cast<std::size_t>(fi.rows) * fi.columns * fi.samples_per_pixel;
    double se = 0;
    std::int64_t me = 0;
    for (std::size_t i = 0; i < n; ++i) {
        const std::int64_t d = sample(a, fi, i) - sample(b, fi, i);
        se += static_cast<double>(d * d);
        me = std::max<std::int64_t>(me, d < 0 ? -d : d);
    }
    if (maxerr) *maxerr = me;
    if (se == 0) return 999.0;
    const double top = static_cast<double>((std::int64_t{1} << fi.bits_stored) - 1);
    return 10.0 * std::log10(top * top * static_cast<double>(n) / se);
}

bool round_trip(const FrameInfo& fi, const j2k::EncodeOptions& o, std::uint32_t seed, double* out_psnr = nullptr,
                std::size_t* out_bytes = nullptr) {
    const auto img = make_image(fi, seed);
    std::vector<std::uint8_t> cs;
    if (Status s = j2k::encode(img, fi, o, cs); !s) {
        std::fprintf(stderr, "  encode: %s\n", s.message.c_str());
        return false;
    }
    std::vector<std::uint8_t> dec(static_cast<std::size_t>(fi.frame_bytes()));
    if (Status s = decode_j2k(cs, fi, dec); !s) {
        std::fprintf(stderr, "  decode: %s\n", s.message.c_str());
        return false;
    }
    if (out_bytes) *out_bytes = cs.size();
    if (o.lossless) return dec == img;
    if (out_psnr) *out_psnr = psnr(img, dec, fi);
    return true;
}

// Compares decode_components output with a vector of reference samples.
bool matches(std::span<const std::uint8_t> cs, std::span<const std::uint16_t> ref, int tol) {
    std::vector<j2k::Component> comps;
    if (Status s = j2k::decode_components(cs, comps); !s) {
        std::fprintf(stderr, "  decode: %s\n", s.message.c_str());
        return false;
    }
    std::size_t k = 0;
    for (const auto& c : comps) {
        for (const auto v : c.samples) {
            if (k >= ref.size()) return false;
            if (std::abs(v - static_cast<std::int32_t>(ref[k++])) > tol) return false;
        }
    }
    return k == ref.size();
}

