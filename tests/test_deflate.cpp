using Buf = std::vector<std::uint8_t>;

Buf bytes_of(const std::string& s) { return Buf(s.begin(), s.end()); }

Buf repeat_text(const std::string& s, int times) {
    std::string r;
    for (int i = 0; i < times; ++i) r += s;
    return bytes_of(r);
}

// Same word generator as the script that produced the oracle vectors.
Buf lcg_text(std::size_t n, std::uint64_t seed) {
    static const char* const words[] = {"pixel", "data",   "frame", "segment", "header", "modality", "study",
                                        "series", "rows", "columns", "window", "level", "\n"};
    Buf out;
    std::uint64_t x = seed;
    while (out.size() < n) {
        x = x * 6364136223846793005ull + 1442695040888963407ull;
        const char* w = words[(x >> 33) % 13];
        out.insert(out.end(), w, w + std::strlen(w));
        out.push_back(' ');
    }
    out.resize(n);
    return out;
}

Buf random_bytes(std::size_t n, std::uint64_t seed) {
    std::mt19937_64 rng(seed);
    Buf b(n);
    for (auto& c : b) c = static_cast<std::uint8_t>(rng());
    return b;
}

